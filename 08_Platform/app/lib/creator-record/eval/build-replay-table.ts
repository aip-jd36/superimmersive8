/**
 * CR-V2-EVIDENCE-SLICE-1 — builds the deterministic fixture-replay table used
 * by the admin prototype's document examination when live extraction is off.
 *
 * For each synthetic fixture: its SHA-256 (from the generated manifest) and
 * the GROUND-TRUTH extraction in the model's output shape, produced by the
 * eval's own offline oracle (`createOracleCaller`, unchanged). This is
 * recorded test data, not model output: replaying it proves the interface and
 * the boundaries, never extraction quality.
 *
 *   python -I lib/creator-record/eval/fixtures/generate_receipt_fixtures.py
 *   npx tsx lib/creator-record/eval/build-replay-table.ts
 *
 * Writes lib/creator-record/evidence/replay-fixtures.data.ts. No model call.
 */

import { writeFileSync } from 'node:fs'
import path from 'node:path'
import { DEFAULT_GENERATED_DIR, loadFixtureSpec, loadManifest, readFixtureBytes, resolveFixtures, specSha256 } from './fixtures'
import { createOracleCaller } from './run-receipt-eval'

export const REPLAY_OUT = path.join(__dirname, '..', 'evidence', 'replay-fixtures.data.ts')

export interface ReplayTableEntry {
  fixture_id: string
  sha256: string
  media_type: string
  bytes: number
  parsed_output: unknown
}

export async function buildReplayEntries(generatedDir = DEFAULT_GENERATED_DIR): Promise<{ spec_version: string; spec_sha256: string; entries: ReplayTableEntry[] }> {
  const spec = loadFixtureSpec()
  const manifest = loadManifest(generatedDir)
  if (!manifest) throw new Error('no generated fixtures: run generate_receipt_fixtures.py first')
  if (manifest.spec_sha256 !== specSha256()) throw new Error('generated fixtures are stale: regenerate them')
  const byId = new Map(resolveFixtures(spec).map((f) => [f.id, f]))
  const entries: ReplayTableEntry[] = []
  for (const m of [...manifest.documents].sort((a, b) => a.id.localeCompare(b.id))) {
    readFixtureBytes(generatedDir, m) // re-checks the manifest hash against the bytes
    const fixture = byId.get(m.id)
    if (!fixture) throw new Error(`manifest entry without a fixture: ${m.id}`)
    const response = await createOracleCaller(fixture)({ content: [], maxTokens: 0 })
    entries.push({ fixture_id: m.id, sha256: m.sha256, media_type: m.media_type, bytes: m.bytes, parsed_output: response.parsed_output })
  }
  return { spec_version: spec.spec_version, spec_sha256: manifest.spec_sha256, entries }
}

export function renderReplayModule(t: Awaited<ReturnType<typeof buildReplayEntries>>): string {
  return [
    '/**',
    ' * GENERATED by lib/creator-record/eval/build-replay-table.ts — do not edit.',
    ' *',
    ' * Ground-truth extractions of SI8\'s SYNTHETIC receipt fixtures, keyed by the',
    ' * fixtures\' SHA-256. Recorded test data, not model output. See',
    ' * `./replay.ts`.',
    ' */',
    '',
    "import type { ReplayFixture } from './replay'",
    '',
    `export const REPLAY_SPEC_VERSION = ${JSON.stringify(t.spec_version)}`,
    `export const REPLAY_SPEC_SHA256 = ${JSON.stringify(t.spec_sha256)}`,
    '',
    `export const REPLAY_FIXTURES: readonly ReplayFixture[] = ${JSON.stringify(t.entries, null, 2)}`,
    '',
  ].join('\n')
}

if (require.main === module) {
  buildReplayEntries()
    .then((t) => {
      writeFileSync(REPLAY_OUT, renderReplayModule(t))
      console.log(`wrote ${t.entries.length} replay entries to ${REPLAY_OUT}`)
    })
    .catch((err) => {
      console.error(err instanceof Error ? err.message : String(err))
      process.exit(1)
    })
}
