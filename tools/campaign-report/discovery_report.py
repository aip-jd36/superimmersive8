#!/usr/bin/env python3
"""
discovery_report.py — SI8 Product Discovery Report Generator

Scans ALL Supabase responses (not just warm) for product discovery signals using
`is_product_feedback()`. This includes pass and naf replies — a polite "not for us"
that describes current workflow or quantifies a pain is more valuable than a vague
warm reply.

Output: 03_Sales/DISCOVERY-PERFORMANCE-LOG.md (latest)
        03_Sales/discovery-reports/DISCOVERY-REPORT-YYYY-MM-DD.md (dated archive)

Usage:
  python tools/campaign-report/discovery_report.py
  python tools/campaign-report/discovery_report.py --supabase data/supabase-exports/supabase-export-YYYY-MM-DD.csv
  python tools/campaign-report/discovery_report.py --dry-run

See 03_Sales/CAMPAIGN-REPORT-METHODOLOGY.md for context on the full report workflow.
"""

import csv, sys, os, re, glob, argparse
from collections import defaultdict
from datetime import date

sys.path.insert(0, os.path.join(os.path.dirname(__file__), '..', 'linkedin-analysis'))
from classify import extract_reply, classify_reply, is_product_feedback

REPO_ROOT   = os.path.abspath(os.path.join(os.path.dirname(__file__), '..', '..'))
OUTPUT_PATH = os.path.join(REPO_ROOT, '03_Sales', 'DISCOVERY-PERFORMANCE-LOG.md')
ARCHIVE_DIR = os.path.join(REPO_ROOT, '03_Sales', 'discovery-reports')

# Geo normalization — kept in sync with report.py
